// seedCatalog imports the curated profile/search options from the supplied catalog.
// It is idempotent: existing rows are updated by their natural names.
func seedCatalog(db *gorm.DB) error {
	return db.Transaction(func(tx *gorm.DB) error {
		for i, name := range catalogProfessions {
			item := domain.CatalogProfession{Name: name, IsActive: true, SortOrder: i + 1}
			if err := tx.Where("name = ?", name).Assign(item).FirstOrCreate(&item).Error; err != nil {
				return err
			}
		}

		for i, name := range catalogServices {
			item := domain.CatalogService{Name: name, IsActive: true, SortOrder: i + 1}
			if err := tx.Where("name = ?", name).Assign(item).FirstOrCreate(&item).Error; err != nil {
				return err
			}
		}

		for _, seed := range catalogBrands {
			brand := domain.VehicleBrand{
				Name:              seed.Name,
				InternationalName: seed.InternationalName,
				IsActive:          true,
				SortOrder:         seed.SortOrder,
			}
			if err := tx.Where("name = ?", seed.Name).Assign(brand).FirstOrCreate(&brand).Error; err != nil {
				return err
			}

			for i, modelName := range seed.Models {
				model := domain.VehicleModel{
					BrandID:   brand.ID,
					Name:      modelName,
					IsActive:  true,
					SortOrder: i + 1,
				}
				if err := tx.Where("brand_id = ? AND name = ?", brand.ID, modelName).
					Assign(model).FirstOrCreate(&model).Error; err != nil {
					return err
				}
			}
		}
		return nil
	})
}
